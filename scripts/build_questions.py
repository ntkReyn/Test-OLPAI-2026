"""Rebuild the browser question bank from the original Markdown (Python 3, no dependencies)."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Ngan_hang_trac_nghiem_OlpAI_UET_2026.md"
SOURCES = [(SOURCE, "easy", 1, 140),
           (ROOT / "Ngan_hang_Trung_binh.md", "medium", 141, 80),
           (ROOT / "Ngan_hang_Kho.md", "hard", 221, 80)]


def parse_questions(text, difficulty="easy", start=1, count=140):
    bank = text.split("# II. ", 1)[1].split("# III. ", 1)[0]
    questions = []
    category = None
    for match in re.finditer(
        r"^## ([A-D])\. (.+)$|^### Câu (\d+) — (.+)\n([\s\S]*?)(?=^### Câu |^## |\Z)",
        bank,
        re.MULTILINE,
    ):
        if match[1]:
            category = {"id": match[1], "name": match[2].strip()}
            continue
        number, title, body = int(match[3]), match[4].strip(), match[5]
        answer = re.search(r"^\*\*Đáp án: ([A-D])\.\*\*\s*([\s\S]+)", body, re.MULTILINE)
        if not answer:
            raise ValueError(f"Câu {number}: thiếu đáp án hoặc giải thích")
        content = body[:answer.start()]
        options = list(re.finditer(r"^([A-D])\. (.*)$", content, re.MULTILINE))
        if [option[1] for option in options] != list("ABCD"):
            raise ValueError(f"Câu {number}: phải có đúng bốn phương án A–D")
        if not category:
            raise ValueError(f"Câu {number}: thiếu chủ đề")
        explanation = re.sub(r"\n---\s*$", "", answer[2]).strip()
        incorrect_explanations = {}
        takeaway = ""
        marker = "**Vì sao các phương án còn lại sai?**"
        if marker not in explanation:
            raise ValueError(f"Câu {number}: thiếu phần giải thích các phương án sai")
        if marker in explanation:
            explanation, analysis = explanation.split(marker, 1)
            analysis, separator, takeaway = analysis.partition("**Ghi nhớ:**")
            entries = list(re.finditer(r"^- \*\*([A-D]):\*\*\s*", analysis, re.MULTILINE))
            for i, entry in enumerate(entries):
                letter = entry[1]
                if letter in incorrect_explanations:
                    raise ValueError(f"Câu {number}: trùng giải thích phương án {letter}")
                incorrect_explanations[letter] = analysis[entry.end():entries[i + 1].start() if i + 1 < len(entries) else len(analysis)].strip()
            if set(incorrect_explanations) != set("ABCD") - {answer[1]} or not all(incorrect_explanations.values()):
                raise ValueError(f"Câu {number}: cần giải thích riêng cả ba phương án sai")
            if not separator or not takeaway.strip() or not explanation.strip():
                raise ValueError(f"Câu {number}: thiếu giải thích đáp án đúng hoặc ghi nhớ")
        questions.append({
            "id": number,
            "difficulty": difficulty,
            "title": title,
            "category": category["id"],
            "categoryName": category["name"],
            "prompt": content[:options[0].start()].strip(),
            "options": [
                {"letter": option[1], "text": content[option.start() + 3:options[i + 1].start() if i + 1 < 4 else len(content)].strip()}
                for i, option in enumerate(options)
            ],
            "answer": answer[1],
            "explanation": explanation.strip(),
            "incorrectExplanations": incorrect_explanations,
            "takeaway": takeaway.strip(),
        })
    if [q["id"] for q in questions] != list(range(start, start + count)):
        raise ValueError(f"Ngân hàng {difficulty}: phải có đủ câu {start}–{start + count - 1}, không trùng hoặc thiếu câu")
    for q in questions:
        if len({o['text'] for o in q['options']}) != 4 or not q['prompt']:
            raise ValueError(f"Câu {q['id']}: nội dung trống hoặc phương án trùng nhau")
    return questions


if __name__ == "__main__":
    questions = [q for source, level, start, count in SOURCES
                 for q in parse_questions(source.read_text(encoding="utf-8-sig"), level, start, count)]
    payload = json.dumps(questions, ensure_ascii=False, indent=2)
    (ROOT / "questions.js").write_text("// Generated by scripts/build_questions.py; edit the Markdown source.\nwindow.QUESTION_BANK = " + payload + ";\n", encoding="utf-8")
    print(f"Đã tạo questions.js: {len(questions)} câu, {len({q['category'] for q in questions})} chủ đề.")
